#!/usr/bin/env python3
"""Writes docs/combat-tests.md: the combat test suite's catalogue (M6, item 3, decided
2026-11-12). Every monster the scripts load (LOAD_MON with a literal id in any ECL block),
with the fights it is in, its special powers (MONnSPC.DAX) and the spells it has memorized,
and the state of its comparison with the original in the lab.

    python3 tools/combat_catalogue.py <POOLRAD folder> > docs/combat-tests.md

Only names and counts from the game files are written, never the records themselves; the
numbers a scenario compares (damage ranges, saves, effects, experience, treasure) are taken
in the lab from the player's own files. COMPARED below is kept by hand as scenarios pass.
Fights the playthrough bot won by shortcut are listed in its counters (skipped_fights) and
are added here by hand as scenarios to run.
"""
import glob
import os
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "lab"))
from dax import read_dax  # noqa: E402
import ecl  # noqa: E402
import unexepack  # noqa: E402
from coverage import POWERS, spell_table  # noqa: E402

# "file:id" -> (state, note). States: compared (a scenario matched the original in the lab),
# differs (a scenario found a difference: the note says which, and the bug), partial.
COMPARED = {
    "7:41": ("partial", "as allies in the last camp battle (lab save D, 2026-11-12): side and starting place beside the party match the original"),
    "7:42": ("partial", "as 7:41"),
    "7:123": ("differs", "last camp battle at 1,14 W, 53 kobolds (lab save D): the original starts them around the party, next to it; ours places them all 2 squares west (5-16 vs the party's 26-31). Placement of a big group near a map edge: to trace"),
}


def main(game):
    img = unexepack.unpack(open(os.path.join(game, "START.EXE"), "rb").read())
    spell_names, _ = spell_table(img)
    fights = defaultdict(set)       # "file:id" -> {"file:block"}
    counts = defaultdict(int)
    for n in range(1, 9):
        path = os.path.join(game, f"ECL{n}.DAX")
        if not os.path.exists(path):
            continue
        for bid, b in read_dax(path).items():
            found, _ = ecl.follow(ecl.code_of(b))
            for name, args, _q in found.values():
                if name == "LOAD_MON" and args[0][0] == 0:
                    key = f"{n}:{args[0][1]}"
                    fights[key].add(f"{n}:{bid}")
                    counts[key] += 1
    out = []
    w = out.append
    w("# Combat test suite: catalogue\n")
    w("Generated by `tools/combat_catalogue.py` from the game files (M6 item 3, decided 2026-11-12)."
      " Every monster a script loads, where it fights, its special powers and memorized spells."
      " A scenario sets the monster against a fixed party in our engine and in the original (the lab),"
      " and compares damage ranges, saving throws, status effects, and experience and treasure."
      " **compared**: matched the original; **differs**: a difference was found (see the note);"
      " blank: no scenario run yet. Power and spell states are in [coverage.md](coverage.md).\n")
    rows = []
    for f in sorted(glob.glob(os.path.join(game, "MON?CHA.DAX"))):
        n = int(os.path.basename(f)[3])
        spc_path = os.path.join(game, f"MON{n}SPC.DAX")
        spc = read_dax(spc_path) if os.path.exists(spc_path) else {}
        for bid, b in sorted(read_dax(f).items()):
            key = f"{n}:{bid}"
            if key not in fights:
                continue
            name = b[1:1 + min(b[0], 15)].decode("ascii", "replace").strip()
            powers = []
            sp = spc.get(bid, b"")
            for i in range(0, len(sp) - 8, 9):
                t = sp[i]
                if t and t in POWERS:
                    powers.append(POWERS[t][1].split(";")[0].split(" (")[0])
                elif t:
                    powers.append(f"effect {t:#04x}")
            spells = sorted({b[k] for k in range(0x17, 0x2C) if k < len(b) and 0 < b[k] < 57})
            rows.append((key, name, sorted(fights[key], key=lambda s: tuple(map(int, s.split(":")))),
                         counts[key], powers, [spell_names[s - 1] for s in spells]))
    done = sum(1 for r in rows if COMPARED.get(r[0], ("",))[0] == "compared")
    w(f"{len(rows)} monster records in fights; {done} compared.\n")
    w("| monster | name | fights in (script blocks) | loads | powers | spells | state | notes |")
    w("|---|---|---|---|---|---|---|---|")
    for key, name, where, n, powers, spells in rows:
        st, note = COMPARED.get(key, ("", ""))
        w(f"| {key} | {name} | {', '.join(where)} | {n} | {'; '.join(powers)} | {', '.join(spells)} | {st} | {note} |")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
