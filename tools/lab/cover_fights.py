#!/usr/bin/env python3
"""Lists the fights coverage runs won by shortcut (M6: each goes on the combat suite's list).

cover_fights.py <log>... > docs/cover-fights.md
Reads the "COVER FIGHT <area> map <m> <x>,<y> [<monster id> x<count>, ...]" lines the bot prints
at the end of each `cover` command and writes one table row per fight (area, map, square,
monsters by record id as in combat-tests.md), merged across logs.
"""
import re, sys
rows = {}
for f in sys.argv[1:]:
    for line in open(f, errors="replace"):
        m = re.match(r"COVER FIGHT (\S+) map (\d+) (\d+,\d+) \[(.*)\]", line.strip())
        if m:
            area, mp, sq, mons = m.groups()
            s = area.split(":")[0]
            mons = ", ".join("%s:%s %s" % (s, x.split(" ")[0], x.split(" ")[1]) for x in mons.split(", ") if x)
            rows[(area, int(mp), sq, mons)] = True
print("# Fights won by shortcut in coverage runs\n")
print("Generated by `tools/lab/cover_fights.py` from the coverage runs' logs (M6, method of 2026-11-13): "
      "every fight a coverage run won at once by shortcut, by area and monsters, with where they met the party (map:square) "
      "(file:record, as in [combat-tests.md](combat-tests.md)) and how many. Each is on the combat suite's "
      "list: the suite tests these fights on their own against the original.\n")
groups = {}
for (area, mp, sq, mons) in rows:
    groups.setdefault((area, mons), []).append("%d:%s" % (mp, sq))
print("| area | monsters | where (map:square) |\n|---|---|---|")
for (area, mons) in sorted(groups, key=lambda g: (int(g[0].split(':')[0]), int(g[0].split(':')[1]), g[1])):
    w = sorted(groups[(area, mons)])
    print("| %s | %s | %s%s |" % (area, mons, ", ".join(w[:6]), " and %d more" % (len(w) - 6) if len(w) > 6 else ""))
